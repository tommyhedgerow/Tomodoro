"""Build image-production/tools/main.swift from variants.py.

The variant grids are authored once, in variants.py. This emits the Swift program
that judges them with the app's real Sources/Core/TortoisePose.swift, so the
Python design tool and the Swift drop-in check can never disagree about what the
art is.

    python3 gen_posecheck.py          # rewrite main.swift
    swiftc -Onone -o /tmp/posecheck ../../Sources/Core/TortoiseSprite.swift \
           ../../Sources/Core/TortoisePose.swift main.swift && /tmp/posecheck

main.swift is generated and disposable. Edit variants.py, not main.swift.
"""

